<?php

namespace App\Support\Filament;

use App\Filament\Auth\CustomLoginPage;
use App\Http\Middleware\OrgMiddleware;
use Filament\Http\Middleware\Authenticate;
use Filament\Http\Middleware\DisableBladeIconComponents;
use Filament\Http\Middleware\DispatchServingFilamentEvent;
use Filament\Panel;
use Filament\Support\Colors\Color;
use Filament\View\PanelsRenderHook;
use Illuminate\Cookie\Middleware\AddQueuedCookiesToResponse;
use Illuminate\Cookie\Middleware\EncryptCookies;
use Illuminate\Foundation\Http\Middleware\VerifyCsrfToken;
use Illuminate\Routing\Middleware\SubstituteBindings;
use Illuminate\Session\Middleware\StartSession;
use Illuminate\View\Middleware\ShareErrorsFromSession;

trait PlatformPanelProvider
{
    /**
     * Common configuration for all panels.
     */
    public function makePanel(Panel $panel, array $authMiddleware = [], string $authenticator = Authenticate::class): Panel
    {
        return $panel
            ->brandName('Platform')
            ->spa()
            // 419 = expired CSRF (e.g. the session regenerated by the impersonation handoff); let
            // Livewire's page-expired reload recover instead of a dead "Error while loading page" toast. DEV-2089.
            ->disabledErrorNotification(419)
            ->login(CustomLoginPage::class)
            ->breadcrumbs(false)
            ->globalSearch(false)
            ->sidebarCollapsibleOnDesktop()
            ->maxContentWidth('full')
            ->colors([
                'primary' => [
                    50 => '#FBE9F5',
                    100 => '#FF6666',
                    200 => '#FF6666',
                    300 => '#FF6666',
                    400 => '#FF6666',
                    500 => '#FF6666',
                    600 => '#FF6666',
                    700 => '#FF6666',
                    800 => '#FF6666',
                    900 => '#FF6666',
                    950 => '#FF6666',
                ],
                'info' => Color::hex('#002dd3'),
                'danger' => Color::hex('#ea580c'),
            ])
            ->databaseNotifications()
            ->databaseNotificationsPolling('60s')
            ->viteTheme('resources/css/filament/app/theme.css')
            ->brandLogo(asset('img/logo-dark.png'))
            ->darkModeBrandLogo(asset('img/logo-dark.png'))
            ->middleware([
                EncryptCookies::class,
                AddQueuedCookiesToResponse::class,
                StartSession::class,
                ShareErrorsFromSession::class,
                VerifyCsrfToken::class,
                SubstituteBindings::class,
                DisableBladeIconComponents::class,
                DispatchServingFilamentEvent::class,
            ])
            ->authMiddleware(\array_merge([
                $authenticator,
                OrgMiddleware::class,
            ], $authMiddleware), isPersistent: true)
            ->renderHook(
                PanelsRenderHook::AUTH_LOGIN_FORM_BEFORE,
                fn (): string => view('prototype.demo-login')->render(),
            );
    }
}
